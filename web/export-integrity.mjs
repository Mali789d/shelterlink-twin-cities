function rotr(x, n) {
  return (x >>> n) | (x << (32 - n));
}

// SHA-256 over the UTF-8 encoding of a string, hex-encoded. Sync by design:
// readDirectory validates synchronously and must stay synchronous.
export function sha256Hex(input) {
  const bytes = new TextEncoder().encode(input);
  const bitLength = bytes.length * 8;
  const paddedLength = (((bytes.length + 8) >> 6) + 1) << 6;
  const buffer = new ArrayBuffer(paddedLength);
  const view = new DataView(buffer);
  new Uint8Array(buffer).set(bytes);
  view.setUint8(bytes.length, 0x80);
  view.setUint32(paddedLength - 4, bitLength >>> 0);
  view.setUint32(paddedLength - 8, Math.floor(bitLength / 2 ** 32));
  const h = [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a,
    0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19];
  const w = new Array(64);
  for (let block = 0; block < paddedLength; block += 64) {
    for (let i = 0; i < 16; i += 1) w[i] = view.getUint32(block + i * 4);
    for (let i = 16; i < 64; i += 1) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) | 0;
    }
    let [a, b, c, d, e, f, g, hh] = h;
    for (let i = 0; i < 64; i += 1) {
      const s1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const temp1 = (hh + s1 + ch + K[i] + w[i]) | 0;
      const s0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const temp2 = (s0 + maj) | 0;
      hh = g; g = f; f = e; e = (d + temp1) | 0;
      d = c; c = b; b = a; a = (temp1 + temp2) | 0;
    }
    h[0] = (h[0] + a) | 0; h[1] = (h[1] + b) | 0; h[2] = (h[2] + c) | 0;
    h[3] = (h[3] + d) | 0; h[4] = (h[4] + e) | 0; h[5] = (h[5] + f) | 0;
    h[6] = (h[6] + g) | 0; h[7] = (h[7] + hh) | 0;
  }
  return h.map(word => (word >>> 0).toString(16).padStart(8, '0')).join('');
}

export function canonicalJson(value) {
  if (value === null || typeof value === 'boolean' || typeof value === 'string') {
    return JSON.stringify(value);
  }
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error('Non-finite numbers cannot be canonicalized');
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) {
    return `[${value.map(canonicalJson).join(',')}]`;
  }
  if (typeof value === 'object') {
    return `{${Object.keys(value).sort()
      .map(key => `${JSON.stringify(key)}:${canonicalJson(value[key])}`).join(',')}}`;
  }
  throw new Error('Unsupported value in export canonical form');
}

// The exact field set app/export_directory.py exports. Injected fields
// (availability, hours, open_now claims) are excluded here and stripped at
// render: the digest covers only what the page may show.
export const EXPORT_RESOURCE_FIELDS = ['address', 'category', 'id', 'latitude',
  'longitude', 'name', 'phone', 'source_name', 'source_url', 'verified_at', 'website'];

export function resourcesDigest(resources) {
  if (!Array.isArray(resources)) throw new Error('Export records must be a list');
  const projected = resources.map(item => {
    if (!item || typeof item !== 'object' || Array.isArray(item)) {
      throw new Error('Invalid export record');
    }
    const record = {};
    for (const key of EXPORT_RESOURCE_FIELDS) {
      if (!(key in item)) throw new Error('Export record misses a reviewed field');
      record[key] = item[key];
    }
    return record;
  });
  return sha256Hex(canonicalJson(projected));
}
